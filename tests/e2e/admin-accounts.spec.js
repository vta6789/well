const { test, expect } = require('@playwright/test');
test.use({ reducedMotion: 'reduce' });

test('administrator reviews real account activity and resets access without revealing stored passwords', async ({ page, playwright }, info) => {
  const origin = 'http://127.0.0.1:8123';
  const learner = await playwright.request.newContext({ baseURL: origin });
  const email = `account-${Date.now()}-${info.project.name}@example.test`;
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    const registration = await learner.post('/api/register', { headers: { Origin: origin }, data: { name: 'Account review learner', email, password: 'Original-account-test-12345' } });
    expect(registration.status()).toBe(200);
    const session = await registration.json();
    const request = async (client, csrf, path, data, method = 'post') => {
      const response = await client[method](`/api/${path}`, { headers: { Origin: origin, 'X-CSRF-Token': csrf }, data });
      expect(response.ok(), await response.text()).toBe(true);
      return response.json();
    };
    const profile = await request(learner, session.csrf, 'residents', { name: 'Review learner profile', dob: '1960-01-01' });
    const login = await request(page.request, '', 'login', { email: 'admin@e2e.test', password: 'Admin-e2e-test-12345' });
    const activity = await request(page.request, login.csrf, 'activities', { name: 'Account review workshop', topic: 'Nông nghiệp', format: 'Workshop', fitness: 'Nhẹ nhàng', date: new Date().toISOString().slice(0, 10), time: '09:00', location: 'Garden', capacity: 5, active: true });
    const packages = await (await learner.get('/api/packages')).json();
    await request(learner, session.csrf, 'bookings', { resident: profile.id, package_id: packages.find(item => item.health_tier === 'month').id, start: new Date().toISOString().slice(0, 10), duration: 1 });
    await request(learner, session.csrf, 'forum', { title: 'My first pot', content: 'Today I learned to grow herbs.' });
    const enrollment = await request(learner, session.csrf, 'enrollments', { resident: profile.id, activity_id: activity.id });
    await request(page.request, login.csrf, `enrollments/${enrollment.id}`, { status: 'Đã tham gia' }, 'patch');
    await request(page.request, login.csrf, 'skills', { resident: profile.id, title: 'Grow herbs', activity_id: activity.id, status: 'Đã học' });
    await request(learner, session.csrf, 'practice', { resident: profile.id, title: 'Practice watering', date: new Date().toISOString().slice(0, 10), notes: 'Used a small watering can.', result: 'One healthy plant.' });
    await request(learner, session.csrf, 'products', { resident: profile.id, name: 'My herb pot', description: 'Planted and watered by the learner.', quantity: 1, unit: 'pot' });
    expect((await learner.get(`/api/users/${session.user.id}/overview`)).status()).toBe(403);
    await page.goto('/');
    await expect(page.locator('.admin-header')).toBeVisible();
    const menu = page.locator('.admin-menu-toggle');
    if (await menu.isVisible()) await menu.click();
    await page.locator('#sidebar [data-page="users"]').click();
    await expect(page.locator('#main th').nth(1)).toHaveText('Email');
    await expect(page.locator('#main th').nth(2)).toHaveText('Mật khẩu');
    await expect(page.locator('#main th').last()).toHaveText('Chi tiết');
    const row = page.locator('#main tbody tr').filter({ hasText: email });
    await row.getByRole('button', { name: 'Chi tiết', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await expect(dialog).toContainText('Review learner profile');
    await expect(dialog).toContainText('Gói Tháng');
    await expect(dialog).toContainText('My first pot');
    await expect(dialog).toContainText('One healthy plant.');
    await expect(dialog).toContainText('Account review workshop');
    await expect(dialog.locator('.account-summary-grid strong')).toHaveText(['1', '1', '1', '1', '1', '1']);
    if (info.project.name === 'mobile') await page.setViewportSize({ width: 320, height: 844 });
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    await page.screenshot({ path: `screenshots/admin-account-detail-${info.project.name}.png` });
    await dialog.locator('.close').click();
    await page.getByRole('button', { name: 'English', exact: true }).click();
    await row.getByRole('button', { name: 'Details', exact: true }).click();
    await expect(dialog).toContainText('Account details · Account review learner');
    await expect(dialog).toContainText('Sessions attended');
    await dialog.locator('.close').click();
    await row.getByRole('button', { name: 'Reset password', exact: true }).click();
    const password = 'Recovery-account-test-12345';
    await dialog.locator('[name="password"]').fill(password);
    await dialog.locator('[type="submit"]').click();
    await expect(dialog.locator('#recovered-password')).toHaveValue(password);
    expect((await learner.get('/api/me')).status()).toBe(401);
    expect((await page.request.get('/api/me')).status()).toBe(200);
    const recovered = await request(learner, '', 'login', { email, password });
    expect(recovered.user.id).toBe(session.user.id);
    await dialog.locator('.close').click();
    await expect(page.locator('#recovered-password')).toHaveValue('');
    const layout = await page.evaluate(() => ({ fits: document.documentElement.scrollWidth <= innerWidth, viewport: innerWidth, width: document.documentElement.scrollWidth, bounds: ['.admin-header', '.admin-header-title', '.admin-header-actions', '.page-head', '.table-wrap', '.admin-main'].map(selector => ({ selector, right: document.querySelector(selector).getBoundingClientRect().right, width: document.querySelector(selector).getBoundingClientRect().width })) }));
    expect(layout.fits, JSON.stringify(layout)).toBe(true);
    expect(errors).toEqual([]);
  } finally { await learner.dispose(); }
});
